import numpy as np
import pandas as pd
from scipy.signal import savgol_filter
import logging
import time
from math import log

logsum_k = {}
logsum_k[0] = 0.0
logsum_k[1] = 0.0


class poisson:
    def __init__(self, mean):
        self.mean = mean

    def get_probability(self, k):
        if self.mean == 0.0:
            return 1.0 if k == 0 else 0.0
        total = -self.mean + k * np.log(self.mean)
        if k not in logsum_k.keys():
            logsum_k[k] = np.sum(np.log(np.arange(2, k + 1, 1.0)))
        total -= logsum_k[k]
        return np.exp(total)

    def update_mean(self, mean):
        self.mean = mean

    def get_mean(self):
        if self.mean < 0:
            logging.warning("Mean is negative, returning 0.0")
            self.mean = 0.0  # Ensure mean is non-negative
            return 0.0
        return self.mean


